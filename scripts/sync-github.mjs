/**
 * Pulls your public GitHub repos into src/content/github.data.ts.
 *
 *   npm run sync:github            (user from portfolio.ts contact.github)
 *   npm run sync:github -- <user>
 *
 * The site (src/content/github.ts) then:
 *   - adds Source / Live links to posters that point at a repo, and
 *   - turns any public repo that isn't on a poster yet into a basic poster
 *     (title, description, languages), while poster slots remain.
 * Forks and empty repos are skipped. Set GITHUB_TOKEN to avoid rate limits.
 * Re-run after publishing something new, then commit the JSON.
 */
import { readFile, writeFile } from 'node:fs/promises';

const portfolio = await readFile('src/content/portfolio.ts', 'utf8');
const user = process.argv[2] ?? portfolio.match(/github:\s*'https:\/\/github\.com\/([^/']+)'/)?.[1];
if (!user) {
  console.error('No GitHub user: pass one, or set contact.github in portfolio.ts');
  process.exit(1);
}

const headers = {
  Accept: 'application/vnd.github+json',
  ...(process.env.GITHUB_TOKEN ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
};
const get = async (url) => {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
};

const list = await get(
  `https://api.github.com/users/${user}/repos?per_page=100&type=owner&sort=pushed`,
);
const repos = [];
for (const r of list) {
  if (r.fork || r.size === 0 || r.archived) continue;
  const languages = await get(r.languages_url).catch(() => ({}));
  repos.push({
    name: r.name,
    description: r.description ?? '',
    url: r.html_url,
    homepage: r.homepage || '',
    languages: Object.entries(languages)
      .sort((a, b) => b[1] - a[1])
      .map(([name]) => name),
    topics: r.topics ?? [],
    stars: r.stargazers_count,
    pushedAt: r.pushed_at,
  });
}

const data = JSON.stringify({ user, syncedAt: new Date().toISOString(), repos }, null, 2);
await writeFile(
  'src/content/github.data.ts',
  `// Generated by \`npm run sync:github\` (scripts/sync-github.mjs). Don't edit by hand.\nexport default ${data};\n`,
);
console.log(`Synced ${repos.length} repos for ${user} -> src/content/github.data.ts`);
